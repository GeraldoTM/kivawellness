let is_modal_open = false;


// influencer banner logic start
const imageGridElem  = document.querySelector('#influencer-banner .image-grid') 
const isBanner = !!imageGridElem

function loadInfluencerBannerImages(){
  let cards = ''
  for (const [key, influencer] of Object.entries(influencer_details)) {
     cards += 
     `<div class="relative influencer-card">
        <div class="influencer-banner__card-overlay">
            <p class="influencer-banner__name">
              ${influencer.name}
            </p>
        </div>
        <img src="${influencer.profile}" class="image influencer__img" width="400" height="400" alt="${influencer.name}" data-key="${key}" loading="lazy"/>
      </div>
     `
  }

  imageGridElem.innerHTML = cards
  imageGridElem.style.gridTemplateColumns = `repeat(${Object.entries(influencer_details).length}, 1fr)`
}

function pauseAnimation(){
  imageGridElem.style.animationPlayState = 'paused';
}
  
function playAnimation(){
  imageGridElem.style.animationPlayState = 'running';
}

if(isBanner){
  imageGridElem.addEventListener('mouseenter', pauseAnimation)
  imageGridElem.addEventListener('mouseleave', () => {
    if (!is_modal_open){
      playAnimation()
    }
  })
}
// influencer banner logic end 

