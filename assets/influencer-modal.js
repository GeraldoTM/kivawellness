//influencer grid logic end

if (isBanner){
  loadInfluencerBannerImages()
}else{
  loadInfluencersCard()
}

function closeModal(){
  const modal = document.getElementsByClassName("influencer-modal")[0]
  if(modal){
    document.body.removeChild(modal)
    if(isBanner){
      playAnimation();
    }
    is_modal_open = false;
  }
}

